const heroCarousel = document.querySelector(".hero-carousel");
if (heroCarousel) {
    const heroSlides = Array.from(heroCarousel.querySelectorAll(".hero-slide"));
    const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    let activeHeroSlide = heroSlides.findIndex((slide) => slide.classList.contains("is-active"));
    let heroTimer;

    function showHeroSlide(index) {
        activeHeroSlide = (index + heroSlides.length) % heroSlides.length;
        heroSlides.forEach((slide, slideIndex) => {
            const isActive = slideIndex === activeHeroSlide;
            slide.classList.toggle("is-active", isActive);
            slide.setAttribute("aria-hidden", String(!isActive));
        });
    }

    function stopHeroTimer() {
        window.clearInterval(heroTimer);
    }

    function startHeroTimer() {
        stopHeroTimer();
        if (!reducedMotion && heroSlides.length > 1) {
            heroTimer = window.setInterval(() => showHeroSlide(activeHeroSlide + 1), 3000);
        }
    }

    heroCarousel.addEventListener("mouseenter", stopHeroTimer);
    heroCarousel.addEventListener("mouseleave", startHeroTimer);
    heroCarousel.addEventListener("focusin", stopHeroTimer);
    heroCarousel.addEventListener("focusout", (event) => {
        if (!heroCarousel.contains(event.relatedTarget)) {
            startHeroTimer();
        }
    });

    showHeroSlide(activeHeroSlide < 0 ? 0 : activeHeroSlide);
    startHeroTimer();
}
