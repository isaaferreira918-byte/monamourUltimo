// OBTENER PRODUCTO DE LA URL
// =================================

const parametros = new URLSearchParams(window.location.search);
const nombreProducto = parametros.get("id") || parametros.get("producto");
const producto = nombreProducto ? productos[nombreProducto] : undefined;

if (!producto) {
    document.getElementById("titulo").textContent = "Producto no encontrado";
    document.getElementById("precio").textContent = "";
    document.getElementById("descripcion").textContent = "No pudimos encontrar este producto.";
    document.querySelector(".imagen-producto").hidden = true;
    document.querySelector(".acciones-producto").hidden = true;
} else {
    const nombreLimpio = producto.nombre.trim();
    const accesorios = new Set(["carteras", "cinturones", "collares", "collar", "llaveros", "pulseras"]);
    const requiereTalle = !accesorios.has(nombreProducto);
    const talles = nombreProducto.startsWith("jean-")
        ? ["36", "38", "40", "42", "44"]
        : ["S", "M", "L"];
    const talleSelector = document.getElementById("talle-selector");
    const tallesOpciones = document.getElementById("talles-opciones");
    const botonComprar = document.getElementById("comprar");
    const estado = document.getElementById("estado-carrito");
    let talleSeleccionado = "";

    document.getElementById("titulo").textContent = nombreLimpio;
    document.getElementById("precio").textContent = producto.precio;
    document.getElementById("breadcrumb-producto").textContent = nombreLimpio;
    document.getElementById("categoria-producto").textContent = nombreProducto.startsWith("jean-")
        ? "Jeans"
        : accesorios.has(nombreProducto) ? "Accesorios" : "Indumentaria";

    const imagen = document.getElementById("img");
    imagen.src = producto.imagenes[0];
    imagen.alt = nombreLimpio;
    imagen.addEventListener("error", () => {
        imagen.alt = `No se pudo cargar la imagen de ${nombreLimpio}`;
    });

    const descripcion = document.getElementById("descripcion");
    descripcion.textContent = "";
    producto.descripcion.forEach((texto) => {
        const parrafo = document.createElement("p");
        parrafo.textContent = texto;
        descripcion.appendChild(parrafo);
    });

    if (requiereTalle) {
        talleSelector.hidden = false;
        talles.forEach((talle) => {
            const opcion = document.createElement("button");
            opcion.className = "talle-opcion";
            opcion.type = "button";
            opcion.textContent = talle;
            opcion.setAttribute("aria-pressed", "false");
            opcion.setAttribute("aria-label", `Talle ${talle}`);
            opcion.addEventListener("click", () => {
                talleSeleccionado = talle;
                tallesOpciones.querySelectorAll(".talle-opcion").forEach((boton) => {
                    boton.setAttribute("aria-pressed", String(boton === opcion));
                });
                estado.textContent = "";
                estado.classList.remove("error");
            });
            tallesOpciones.appendChild(opcion);
        });
    }

    botonComprar.addEventListener("click", (evento) => {
        if (requiereTalle && !talleSeleccionado) {
            evento.preventDefault();
            estado.textContent = "Elegí un talle para continuar con la compra.";
            estado.classList.add("error");
            return;
        }
        estado.textContent = "";
        estado.classList.remove("error");
    });

    document.getElementById("agregar-carrito").addEventListener("click", () => {
        if (requiereTalle && !talleSeleccionado) {
            estado.textContent = "Elegí un talle antes de agregar el producto al carrito.";
            estado.classList.add("error");
            return;
        }

        try {
            const idCarrito = talleSeleccionado
                ? `${nombreProducto}-${talleSeleccionado}`
                : nombreProducto;
            const nombreCarrito = talleSeleccionado
                ? `${nombreLimpio} (Talle ${talleSeleccionado})`
                : nombreLimpio;
            const productoCarrito = {
                id: idCarrito,
                nombre: nombreCarrito,
                talle: talleSeleccionado || null,
                precio: producto.precio,
                precioNumero: Number(String(producto.precio).replace(/[^\d,.-]/g, "").replace(/\./g, "").replace(",", ".")) || 0,
                imagen: producto.imagenes[0]
            };

            if (typeof window.MonamourCart?.agregarProductoAlCarrito === "function") {
                window.MonamourCart.agregarProductoAlCarrito(productoCarrito);
            } else {
                const contenido = localStorage.getItem("monamour-carrito");
                const carrito = contenido ? JSON.parse(contenido) : [];
                if (!Array.isArray(carrito)) {
                    throw new Error("El carrito guardado no tiene un formato válido.");
                }

                const productoEnCarrito = carrito.find((item) => item.id === idCarrito);
                if (productoEnCarrito) {
                    if (!Number.isInteger(productoEnCarrito.cantidad) || productoEnCarrito.cantidad < 1) {
                        throw new Error("La cantidad guardada para este producto no es válida.");
                    }
                    productoEnCarrito.cantidad += 1;
                } else {
                    carrito.push({
                        id: idCarrito,
                        nombre: nombreCarrito,
                        talle: talleSeleccionado || null,
                        precio: producto.precio,
                        precioNumero: productoCarrito.precioNumero,
                        imagen: producto.imagenes[0],
                        cantidad: 1
                    });
                }

                localStorage.setItem("monamour-carrito", JSON.stringify(carrito));
            }

            estado.textContent = `${nombreCarrito} se agregó al carrito.`;
            estado.classList.remove("error");
        } catch (error) {
            console.error("No se pudo guardar el producto en el carrito.", error);
            estado.textContent = "No se pudo guardar el producto. Revisá la configuración del navegador e intentá nuevamente.";
            estado.classList.add("error");
        }
    });
}
