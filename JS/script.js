const CART_KEY = "monamour-carrito";

function parsePrecioNumerico(precio) {
    const valor = String(precio ?? "$0")
        .replace(/[^\d,.-]/g, "")
        .replace(/\./g, "")
        .replace(",", ".");

    const numero = Number.parseFloat(valor);
    return Number.isFinite(numero) ? numero : 0;
}

function formatearPrecio(valor) {
    return new Intl.NumberFormat("es-AR", {
        style: "currency",
        currency: "ARS",
        maximumFractionDigits: 0
    }).format(valor);
}

function obtenerCarrito() {
    try {
        const contenido = localStorage.getItem(CART_KEY);
        const carrito = contenido ? JSON.parse(contenido) : [];
        return Array.isArray(carrito) ? carrito : [];
    } catch (error) {
        console.error("No se pudo leer el carrito.", error);
        return [];
    }
}

function guardarCarrito(carrito) {
    localStorage.setItem(CART_KEY, JSON.stringify(carrito));
}

function calcularTotalCarrito(carrito) {
    return carrito.reduce((total, item) => {
        const cantidad = Number(item.cantidad) || 1;
        const precio = Number(item.precioNumero) || parsePrecioNumerico(item.precio || "$0");
        return total + precio * cantidad;
    }, 0);
}

function renderCart() {
    const cartPanel = document.getElementById("carrito");
    const cartItems = document.getElementById("carrito-items");
    const cartTotal = document.getElementById("carrito-total");
    const cartCount = document.querySelector("[data-cart-count]");
    const cartButton = document.querySelector("[data-cart-toggle]");
    const checkoutButton = document.querySelector(".checkout-button");

    if (!cartItems || !cartTotal || !cartCount) {
        return;
    }

    const carrito = obtenerCarrito();
    const totalCantidad = carrito.reduce((total, item) => total + (Number(item.cantidad) || 1), 0);
    cartCount.textContent = totalCantidad;

    if (!carrito.length) {
        cartItems.innerHTML = '<p class="cart-empty">Tu carrito está vacío.</p>';
        cartTotal.textContent = "$0";
        if (checkoutButton) {
            checkoutButton.disabled = true;
            checkoutButton.style.opacity = "0.6";
            checkoutButton.style.cursor = "not-allowed";
        }
        return;
    }

    if (checkoutButton) {
        checkoutButton.disabled = false;
        checkoutButton.style.opacity = "1";
        checkoutButton.style.cursor = "pointer";
    }

    cartItems.innerHTML = carrito.map((item) => {
        const cantidad = Number(item.cantidad) || 1;
        const precioNumero = Number(item.precioNumero) || parsePrecioNumerico(item.precio || "$0");
        const subtotal = precioNumero * cantidad;

        return `
            <div class="cart-item">
                <img src="${item.imagen || ""}" alt="${item.nombre || "Producto"}">
                <div class="cart-item-info">
                    <h3>${item.nombre || "Producto"}</h3>
                    <p>${formatearPrecio(precioNumero)} cada uno</p>
                    <div class="cart-item-controls">
                        <button type="button" class="cart-qty-btn" data-cart-action="decrease" data-cart-id="${item.id}">-</button>
                        <span>${cantidad}</span>
                        <button type="button" class="cart-qty-btn" data-cart-action="increase" data-cart-id="${item.id}">+</button>
                    </div>
                </div>
                <strong>${formatearPrecio(subtotal)}</strong>
            </div>
        `;
    }).join("");

    cartTotal.textContent = formatearPrecio(calcularTotalCarrito(carrito));

    document.querySelectorAll("[data-cart-action]").forEach((boton) => {
        boton.addEventListener("click", () => {
            const itemId = boton.dataset.cartId;
            const accion = boton.dataset.cartAction;
            const carritoActualizado = obtenerCarrito().map((item) => {
                if (item.id !== itemId) {
                    return item;
                }

                const nuevaCantidad = accion === "increase" ? (Number(item.cantidad) || 1) + 1 : (Number(item.cantidad) || 1) - 1;
                return { ...item, cantidad: Math.max(0, nuevaCantidad) };
            }).filter((item) => Number(item.cantidad) > 0);

            guardarCarrito(carritoActualizado);
            renderCart();
        });
    });

    if (cartButton) {
        cartButton.setAttribute("aria-expanded", cartPanel && cartPanel.classList.contains("open") ? "true" : "false");
    }
}

function abrirCarrito() {
    const cartPanel = document.getElementById("carrito");
    if (cartPanel) {
        cartPanel.classList.add("open");
    }
}

function cerrarCarrito() {
    const cartPanel = document.getElementById("carrito");
    if (cartPanel) {
        cartPanel.classList.remove("open");
    }
}

function agregarProductoAlCarrito(producto) {
    const carrito = obtenerCarrito();
    const itemId = String(producto.id || producto.nombre || "producto").trim();
    const itemExistente = carrito.find((item) => item.id === itemId);

    const productoAgregado = {
        id: itemId,
        nombre: producto.nombre,
        precio: producto.precio,
        precioNumero: Number(producto.precioNumero) || parsePrecioNumerico(producto.precio || "$0"),
        imagen: producto.imagen,
        cantidad: 1
    };

    if (itemExistente) {
        itemExistente.cantidad = (Number(itemExistente.cantidad) || 1) + 1;
        itemExistente.precioNumero = Number(itemExistente.precioNumero) || parsePrecioNumerico(itemExistente.precio || "$0");
    } else {
        carrito.push(productoAgregado);
    }

    guardarCarrito(carrito);
    renderCart();
    abrirCarrito();
    return carrito;
}

window.MonamourCart = {
    obtenerCarrito,
    guardarCarrito,
    agregarProductoAlCarrito,
    renderCart,
    abrirCarrito,
    cerrarCarrito,
    calcularTotalCarrito
};

